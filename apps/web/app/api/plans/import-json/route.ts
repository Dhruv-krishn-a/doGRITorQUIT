import { NextResponse } from "next/server";
import { getServerUser } from "@/lib/auth";
import { prisma } from "@/lib/prisma";

// ✅ FIX: Define the expected shape of the incoming JSON task
interface ImportTask {
  Day?: number;
  "Task Title"?: string;
  Description?: string;
  "Estimated Time (min)"?: number;
  Priority?: string;
  Subtasks?: string[];
}

export async function POST(req: Request) {
  try {
    const user = await getServerUser();
    if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

    // 🟢 LIMIT CHECK REMOVED (Single Source of Truth is AI Credits)

    const body = await req.json();
    const { planName, tasks, startDate, isAI } = body ?? {};

    if (!tasks || !Array.isArray(tasks)) {
      return NextResponse.json({ error: "Invalid tasks data" }, { status: 400 });
    }

    // Calculate start date
    const startObj = new Date(startDate);

    // Transaction to create Plan + Tasks + Subtasks
    const createdPlan = await prisma.plan.create({
      data: {
        userId: user.id,
        title: planName,
        description: isAI ? "Generated by AI Architect" : "Imported Plan",
        startDate: startObj,
        tasks: {
          // ✅ FIX: Use the 'ImportTask' interface instead of 'any'
          create: tasks.map((t: ImportTask) => {
            // Calculate specific date based on "Day" offset
            const taskDate = new Date(startObj);
            const dayOffset = (t.Day || 1) - 1;
            taskDate.setDate(taskDate.getDate() + dayOffset);

            return {
              userId: user.id, 
              title: t["Task Title"] || "Untitled Task",
              description: t.Description || "",
              estimatedMinutes: t["Estimated Time (min)"] || 30,
              priority: t.Priority || "Medium",
              date: taskDate,
              status: "Pending",
              subtasks: {
                create: (t.Subtasks || []).map((subTitle: string) => ({
                  title: subTitle,
                  completed: false
                }))
              }
            };
          })
        }
      },
      include: {
        tasks: {
          include: { subtasks: true }
        }
      }
    });

    return NextResponse.json(createdPlan, { status: 201 });
  } catch (error) {
    console.error("Import JSON error:", error);
    const message = error instanceof Error ? error.message : "Import failed";
    return NextResponse.json({ error: message }, { status: 500 });
  }
}